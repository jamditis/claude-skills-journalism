"""Contract tests for the no-ai-attribution PreToolUse hook.

The hook blocks a git/gh command that would write AI authorship credit into the
project record, before it runs. It reads the Claude Code PreToolUse payload on
stdin and exits 2 to deny (reason on stderr) or 0 to allow.

These tests drive the implementation: they define exactly which command shapes
must block, which must pass, and how the hook fails open. Run:
    python -m pytest hooks/tests/test_no_ai_attribution.py -q
"""
import json
import subprocess
import sys
from pathlib import Path

HOOK = Path(__file__).resolve().parent.parent / "no-ai-attribution.py"

DENY = 2
ALLOW = 0


def run(command, tool_name="Bash", cwd=None, raw_stdin=None, timeout=30):
    """Invoke the hook as a subprocess with a PreToolUse payload; return CompletedProcess.

    timeout guards the never-wedge contract: if the hook hangs (e.g. reading a FIFO),
    subprocess.run raises TimeoutExpired and kills the child, so a hang fails the test
    loudly instead of freezing the suite.
    """
    if raw_stdin is None:
        payload = {"tool_name": tool_name, "tool_input": {"command": command}}
        if cwd is not None:
            payload["cwd"] = str(cwd)
        stdin = json.dumps(payload)
    else:
        stdin = raw_stdin
    return subprocess.run(
        [sys.executable, str(HOOK)],
        input=stdin,
        capture_output=True,
        text=True,
        timeout=timeout,
    )


def assert_blocked(r):
    # A real deny is exit 2 with the hook's own reason on stderr. Requiring the
    # sentinel distinguishes a genuine block from a crash (a missing script also
    # exits 2, with a traceback instead of the reason).
    assert r.returncode == DENY and "no-ai-attribution" in r.stderr.lower(), (
        r.returncode,
        r.stderr,
    )


def assert_allowed(r):
    assert r.returncode == ALLOW, (r.returncode, r.stderr)


