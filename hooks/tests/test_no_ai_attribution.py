def test_fifo_body_file_fails_open_without_hanging(tmp_path):
    # A FIFO body-file would block a naive read forever. The hook must treat a
    # non-regular file as unreadable and fail open, returning quickly.
    import os
    fifo = tmp_path / "PIPE"
    os.mkfifo(fifo)
    r = run("gh pr create --body-file PIPE", cwd=tmp_path, timeout=15)
    assert_allowed(r)


def test_large_regular_body_file_with_early_attribution_blocks(tmp_path):
    # A large but regular file is read up to the cap; attribution near the top is
    # still caught, and the read does not exhaust memory.
    body = tmp_path / "BIG.md"
    body.write_text("\U0001F916 Generated with Claude Code\n" + ("filler line\n" * 200000))
    r = run("gh pr create --body-file BIG.md", cwd=tmp_path)
    assert_blocked(r)


